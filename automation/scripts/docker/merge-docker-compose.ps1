param(
  [Parameter(ValueFromRemainingArguments = $true)]
  [string[]] $DockerComposeArgs = @()
)

if ([string]::IsNullOrWhiteSpace($env:GAMESAPP_ENV_FILE)) {
    $env:GAMESAPP_ENV_FILE = ".env"
}

$EnvFile = $env:GAMESAPP_ENV_FILE

if ([string]::IsNullOrWhiteSpace($env:GAMESAPP_DOCKER_PROFILE)) {
    $env:GAMESAPP_DOCKER_PROFILE = "local"
}

$DockerProfile = $env:GAMESAPP_DOCKER_PROFILE

$ThisScript = $MyInvocation.MyCommand.Path
$ScriptDir = Split-Path -Parent $ThisScript
while ($ScriptDir -and -not (Test-Path (Join-Path $ScriptDir "docker-compose.shared.yml"))) {
    $parent = Split-Path $ScriptDir -Parent
    if ([string]::IsNullOrEmpty($parent) -or $parent -eq $ScriptDir) {
        Write-Error "Could not find project root (docker-compose.shared.yml) starting from $ThisScript"
        exit 1
    }
    $ScriptDir = $parent
}
Set-Location $ScriptDir

function ConvertTo-WSLPath {
    param([string] $WindowsPath)

    if (-not [string]::IsNullOrWhiteSpace($WindowsPath)) {
        if ($WindowsPath -match '^([A-Z]):\\(.+)') {
            $DriveLetter = $Matches[1].ToLower()
            $RemainingPath = $Matches[2] -replace '\\', '/'
            return "/mnt/$DriveLetter/$RemainingPath"
        }
        return $WindowsPath
    }
    return $WindowsPath
}

function Ensure-RootWslPathInEnvFile {
    param([string] $EnvFileFullPath, [string] $RootWslPath)
    if ([string]::IsNullOrWhiteSpace($RootWslPath)) { return }
    if (-not (Test-Path $EnvFileFullPath)) { return }
    $comment = "# Project root in WSL format (auto-generated by merge-docker-compose.ps1; used for volume mounts)"
    $entry = "ROOT_WSL_PATH=$RootWslPath"
    $content = Get-Content -Path $EnvFileFullPath -Raw
    if ($content -match 'ROOT_WSL_PATH\s*=') { return }
    Add-Content -Path $EnvFileFullPath -Value "`n$comment`n$entry" -Encoding UTF8
    Write-Host "Added ROOT_WSL_PATH to $EnvFileFullPath" -ForegroundColor Cyan
}

$EnvFilePath = $EnvFile
if (-not [System.IO.Path]::IsPathRooted($EnvFile)) {
    $EnvFilePath = Join-Path $ScriptDir $EnvFile
}

$env:API_ENV_FILE_PATH = $EnvFilePath

$RootWslPath = ConvertTo-WSLPath $ScriptDir
Ensure-RootWslPathInEnvFile -EnvFileFullPath $EnvFilePath -RootWslPath $RootWslPath

$ServiceComposeFiles = @()
$ServiceRoot = Join-Path $ScriptDir "src\services"

if (-not (Test-Path $ServiceRoot)) {
    Write-Error "Service root directory not found: $ServiceRoot"
    exit 1
}

foreach ($ServiceDir in (Get-ChildItem -Path $ServiceRoot -Directory -ErrorAction SilentlyContinue)) {
    $ProfileDockerDir = Join-Path (Join-Path $ServiceDir.FullName ".docker") $DockerProfile
    if (-not (Test-Path $ProfileDockerDir)) { continue }

    $ComposeFile = Join-Path $ProfileDockerDir "docker-compose.yml"
    if (Test-Path $ComposeFile) {
        $ServiceComposeFiles += $ComposeFile
        Write-Host "Found compose file: $ComposeFile" -ForegroundColor Green
    }

    $DevComposeFile = Join-Path $ProfileDockerDir "docker-compose.dev.yml"
    if (Test-Path $DevComposeFile) {
        $ServiceComposeFiles += $DevComposeFile
        Write-Host "Found dev compose file: $DevComposeFile" -ForegroundColor Green
    }
}

if ($ServiceComposeFiles.Count -eq 0) {
    Write-Error "No service compose files found in $ServiceRoot"
    exit 1
}

$SharedResourcesFile = Join-Path $ScriptDir "docker-compose.shared.yml"
$ComposeFiles = @()
if (Test-Path $SharedResourcesFile) {
    $ComposeFiles += "-f"
    $ComposeFiles += $SharedResourcesFile
    Write-Host "Including shared resources: $SharedResourcesFile" -ForegroundColor Green
}

foreach ($File in $ServiceComposeFiles) {
    $ComposeFiles += "-f"
    $ComposeFiles += $File
}

$DockerComposeCmd = "docker"
$AllArgs = @("compose", "--env-file", $EnvFilePath) + $ComposeFiles + $DockerComposeArgs

if ($DockerComposeArgs.Count -eq 0) {
    Write-Host "`nGamesApp Docker Compose merge helper`n" -ForegroundColor Cyan
    Write-Host "Environment:" -ForegroundColor Yellow
    Write-Host "  `$env:GAMESAPP_ENV_FILE (default: .env)" -ForegroundColor Gray
    Write-Host "  `$env:GAMESAPP_DOCKER_PROFILE (default: local)`n" -ForegroundColor Gray
    Write-Host "Examples:" -ForegroundColor Yellow
    Write-Host "  .\merge-docker-compose.ps1 up -d" -ForegroundColor Gray
    Write-Host "  .\merge-docker-compose.ps1 up -d postgresql keycloak api ui" -ForegroundColor Gray
    Write-Host "  `$env:GAMESAPP_ENV_FILE='.env.prod'; .\merge-docker-compose.ps1 up -d`n" -ForegroundColor Gray
    Write-Host "Compose files:" -ForegroundColor Cyan
    foreach ($File in $ServiceComposeFiles) {
        Write-Host "  - $File" -ForegroundColor Gray
    }
    if (Test-Path $SharedResourcesFile) {
        Write-Host "  - $SharedResourcesFile" -ForegroundColor Gray
    }
    exit 0
}

if (-not (Test-Path $EnvFilePath)) {
    Write-Warning "Environment file not found: $EnvFilePath"
    Write-Warning "Continuing without --env-file ..."
    $AllArgs = @("compose") + $ComposeFiles + $DockerComposeArgs
}
else {
    Write-Host "Using environment file: $EnvFilePath" -ForegroundColor Green
}

Write-Host "`nExecuting: docker compose $(($AllArgs | Select-Object -Skip 1) -join ' ')`n" -ForegroundColor Cyan
$env:DOCKER_BUILDKIT = "0"

try {
    & $DockerComposeCmd $AllArgs
    $ExitCode = $LASTEXITCODE
    if ($ExitCode -ne 0) {
        Write-Error "Docker Compose command failed with exit code $ExitCode"
        exit $ExitCode
    }
}
catch {
    Write-Error "Failed to execute Docker Compose: $_"
    exit 1
}
